"""Build the two photographed shelf items from product photos: Happydent Wave gum pot and Savemore sponge pack.

For each item this writes, into assets/custom/<item>/:
  <item>.obj   chamfered-box mesh with texture coordinates (also the collision shape: a convex hull is exact)
  <item>.png   texture atlas cut out of the photos
  <item>.xml   MuJoCo model (real size, metres, z up, base at z = 0, footprint centred on the origin)

Photos needed (any 4 images, named like this in --photos):
  1.png  sponge pack, front, shot from above      2.png  sponge pack from the side (stacked pads)
  3.png  Happydent pot, front (label)             4.png  Happydent pot, side

Usage:  uv run python scripts/build_item_assets.py --photos <dir>
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

OUT_ROOT = Path(__file__).resolve().parents[1] / "assets" / "custom"
ATLAS = 1024


# ---------------------------------------------------------------- image helpers
def quad_to_rect(img: Image.Image, quad, size) -> Image.Image:
    """Perspective-correct the photographed quad (TL, TR, BR, BL pixel corners) into an upright `size` image."""
    w, h = size
    src = np.array(quad, float)
    dst = np.array([[0, 0], [w, 0], [w, h], [0, h]], float)
    rows = []
    for (x, y), (u, v) in zip(dst, src):
        rows.append([x, y, 1, 0, 0, 0, -u * x, -u * y])
        rows.append([0, 0, 0, x, y, 1, -v * x, -v * y])
    coef = np.linalg.solve(np.array(rows), src.reshape(-1))
    return img.transform(size, Image.PERSPECTIVE, coef.tolist(), Image.BICUBIC)


def paste_tile(atlas: Image.Image, tile: Image.Image, rect) -> None:
    """rect = (u0, v0, u1, v1) in 0..1 with v measured from the bottom of the atlas."""
    u0, v0, u1, v1 = rect
    px0, px1 = round(u0 * ATLAS), round(u1 * ATLAS)
    py0, py1 = round((1 - v1) * ATLAS), round((1 - v0) * ATLAS)
    atlas.paste(tile.resize((px1 - px0, py1 - py0), Image.LANCZOS), (px0, py0))


# ---------------------------------------------------------------- mesh
class Mesh:
    def __init__(self) -> None:
        self.v: list[list[float]] = []
        self.vt: list[list[float]] = []
        self.f: list[tuple[int, int, int]] = []

    def quad(self, origin, u_axis, v_axis, rect) -> None:
        """A planar quad: origin + {0,1} * u_axis + {0,1} * v_axis. u x v must point outward. rect = atlas (u0,v0,u1,v1)."""
        o, u, v = np.array(origin, float), np.array(u_axis, float), np.array(v_axis, float)
        u0, v0, u1, v1 = rect
        base = len(self.v)
        for p, t in ((o, (u0, v0)), (o + u, (u1, v0)), (o + u + v, (u1, v1)), (o + v, (u0, v1))):
            self.v.append(list(p))
            self.vt.append(list(t))
        self.f += [(base, base + 1, base + 2), (base, base + 2, base + 3)]

    def fan(self, ring, z, up: bool, rect, centre) -> None:
        """Cap polygon (ring is CCW seen from +z) as a fan; planar UVs spread over `rect`."""
        u0, v0, u1, v1 = rect
        xs = [p[0] for p in ring]
        ys = [p[1] for p in ring]
        x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)

        def uv(x, y):
            return (u0 + (x - x0) / (x1 - x0) * (u1 - u0), v0 + (y - y0) / (y1 - y0) * (v1 - v0))

        pts = [(centre[0], centre[1])] + list(ring)
        base = len(self.v)
        for x, y in pts:
            self.v.append([x, y, z])
            self.vt.append(list(uv(x, y)))
        n = len(ring)
        for i in range(n):
            a, b = base + 1 + i, base + 1 + (i + 1) % n
            self.f.append((base, a, b) if up else (base, b, a))

    def write(self, path: Path) -> None:
        lines = ["# generated by scripts/build_item_assets.py"]
        lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in self.v]
        lines += [f"vt {u:.5f} {v:.5f}" for u, v in self.vt]
        lines += [f"f {a + 1}/{a + 1} {b + 1}/{b + 1} {c + 1}/{c + 1}" for a, b, c in self.f]
        path.write_text("\n".join(lines) + "\n")


def chamfered_prism(hx, hy, height, chamfer, side_rects, top_rect, bottom_rect, edge_rect) -> Mesh:
    """Box with its four vertical edges chamfered. side_rects: atlas rect for the faces with normal +x, +y, -x, -y."""
    c = chamfer
    ring = [(hx, -hy + c), (hx, hy - c), (hx - c, hy), (-hx + c, hy), (-hx, hy - c), (-hx, -hy + c), (-hx + c, -hy), (hx - c, -hy)]
    m = Mesh()
    z_axis = np.array([0.0, 0.0, height])
    for i, p in enumerate(ring):
        q = ring[(i + 1) % len(ring)]
        d = np.array([q[0] - p[0], q[1] - p[1], 0.0])
        if i % 2 == 0:  # flat face: normal +x, +y, -x, -y
            rect = side_rects[i // 2]
        else:
            rect = edge_rect
        m.quad([p[0], p[1], 0.0], d, z_axis, rect)
    m.fan(ring, height, True, top_rect, (0.0, 0.0))
    m.fan(ring[::-1], 0.0, False, bottom_rect, (0.0, 0.0))
    return m


# ---------------------------------------------------------------- items
def xml(name: str, comment: str, density: float, extra: str = "") -> str:
    return f"""<mujoco model="{name}">
  <!-- {comment} -->
  <asset>
    <texture name="tex" type="2d" file="{name}.png"/>
    <material name="mat" texture="tex" specular="0.25" shininess="0.35"/>
    <mesh name="shape" file="{name}.obj"/>
  </asset>
  <worldbody>
    <body>
      <body name="object">
        <geom name="body" type="mesh" mesh="shape" material="mat" density="{density}" friction="0.9 0.3 0.1"/>{extra}
      </body>
    </body>
  </worldbody>
</mujoco>
"""


def build_happydent(photos: Path) -> None:
    out = OUT_ROOT / "happydent_wave"
    out.mkdir(parents=True, exist_ok=True)
    front = Image.open(photos / "3.png").convert("RGB").crop((300, 332, 658, 1092))
    side = Image.open(photos / "4.png").convert("RGB").crop((330, 362, 590, 1135))
    atlas = Image.new("RGB", (ATLAS, ATLAS), (214, 31, 135))
    F, S, P = (0.0, 0.0, 0.5, 1.0), (0.5, 0.0, 0.75, 1.0), (0.75, 0.0, 1.0, 1.0)
    paste_tile(atlas, front, F)
    paste_tile(atlas, side, S)
    cap = Image.new("RGB", (256, 1024), (214, 31, 135))  # pink cap top with the round white sticker
    # the printed label on the cap top (cut from the side photo, seen at a low angle), stretched into a round sticker
    sticker = Image.open(photos / "4.png").convert("RGB").crop((392, 364, 552, 408)).resize((192, 571), Image.LANCZOS)
    mask = Image.new("L", (192, 571), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, 191, 570), fill=255)
    cap.paste(sticker, (32, 226), mask)  # a 2.4 cm sticker on the 3.2 x 4.3 cm top
    paste_tile(atlas, cap, P)
    pink = (0.76, 0.02, 0.78, 0.04)  # a corner of the cap tile that is plain pink
    # 4.3 cm wide (y, the label face) x 3.2 cm deep (x) x 8.8 cm tall, as measured against the photos
    # face order is +x, +y, -x, -y: the label (the wide face) is on +x
    mesh = chamfered_prism(0.016, 0.0215, 0.088, 0.006, [F, S, S, S], P, pink, pink)
    mesh.write(out / "happydent_wave.obj")
    atlas.save(out / "happydent_wave.png")
    (out / "happydent_wave.xml").write_text(
        xml("happydent_wave", "Happydent Wave sugar-free gum pot (pink, hinged cap), real size in metres, z up: 4.3 cm (y, label face) x 3.2 cm (x) x 8.8 cm. Label faces +x.", 500)
    )


def build_sponge(photos: Path) -> None:
    out = OUT_ROOT / "sponge_pack"
    out.mkdir(parents=True, exist_ok=True)
    top = quad_to_rect(Image.open(photos / "1.png").convert("RGB"), [(205, 205), (692, 215), (562, 1008), (62, 985)], (490, 780))
    side = quad_to_rect(Image.open(photos / "2.png").convert("RGB"), [(628, 146), (1452, 198), (1336, 508), (620, 376)], (820, 340))
    atlas = Image.new("RGB", (ATLAS, ATLAS), (214, 208, 40))
    T, S, E = (0.0, 0.0, 0.5, 1.0), (0.5, 0.0, 1.0, 0.5), (0.52, 0.52, 0.54, 0.54)
    paste_tile(atlas, top, T)
    paste_tile(atlas, side, S)
    ImageDraw.Draw(atlas).rectangle((ATLAS // 2, 0, ATLAS, ATLAS // 2), fill=(206, 205, 44))  # plain end-seal colour (v 0.5..1)
    # Standing on its long edge so the jaws (which open along x) pinch the 4.6 cm thickness:
    # 4.6 cm (x) x 11 cm (y, front to back) x 7 cm (z). The big label faces are +x / -x (the faces the jaws close on),
    # the stack of pads shows on top, the crimped film seals are at the front and back (+y / -y).
    label = top.rotate(90, expand=True)  # portrait label -> landscape: its long side runs along y
    paste_tile(atlas, label, T)
    mesh = chamfered_prism(0.023, 0.055, 0.070, 0.006, [T, E, T, E], S, S, E)
    # fan() maps x -> u, y -> v; the stripes picture is landscape, so its long side must run along y: swap
    n_side = 8 * 4
    for block in (n_side, n_side + 9):
        for k in range(block, block + 9):
            x, y, _ = mesh.v[k]
            u0, v0, u1, v1 = S
            mesh.vt[k] = [u0 + (y + 0.055) / 0.11 * (u1 - u0), v0 + (x + 0.023) / 0.046 * (v1 - v0)]
    mesh.write(out / "sponge_pack.obj")
    atlas.save(out / "sponge_pack.png")
    flaps = """
        <geom name="seal_a" type="box" pos="0 0.0625 0.035" size="0.0015 0.0075 0.030" contype="0" conaffinity="0" group="2" mass="0.0001" rgba="0.80 0.78 0.16 1"/>
        <geom name="seal_b" type="box" pos="0 -0.0625 0.035" size="0.0015 0.0075 0.030" contype="0" conaffinity="0" group="2" mass="0.0001" rgba="0.12 0.55 0.22 1"/>"""
    (out / "sponge_pack.xml").write_text(
        xml("sponge_pack", "Savemore Sponge Scrub, pack of 2 pads in film, standing on its long edge so the jaws pinch the 4.6 cm thickness. Real size in metres, z up: 4.6 cm (x) x 11 cm (y) x 7 cm (z), plus crimped end seals. Label faces +x/-x.", 250, flaps)
    )


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--photos", type=Path, required=True)
    args = parser.parse_args()
    build_happydent(args.photos)
    build_sponge(args.photos)
    print(f"[ok] wrote happydent_wave and sponge_pack to {OUT_ROOT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
